r"""W2L CORRECTED-CONNECTOME campaign (2026-10-20, egg; Ben's ask: "run the
updated connectome in MuJoCo SNS toolbox and tune it").

Net: --net=bilateralrg2 = Ben's 2026-10-18 corrected aproj (physical
contact sensing closed, Li-style chain) via w2l_cpg.build_w2l_net
(census 96/204; template generated by w2l_cpg/make_bilateralrg2.py - read
its docstring for the 7-point wiring delta and the 2 flagged items).

Stage 1 (this driver, default): full tune at bootstrap drive scale 1.0 -
optuna TPE over drive (te, tf) + the corrected contact-family gains
(ch_hc heel cascade, ch_ank ankle contact, ch_contra the NEW crossed
heel->contra-RG-flx edge) + sensor encoding (ctn_amp, cref, ibnA) +
commissural scale (comm). Protocol/body knobs pinned at the wean
campaign's bootstrap winner (legcoll 0, sink 0.06, rig 0.25,
walker_yield 1.5).

Metric = the wean campaign's objective + survival gate VERBATIM
(_w2l_wean_eval; objective_from + survive criterion), so results are
directly comparable to the aff-lineage record (obj 94.86 @ dscale 0.6).

Anti-lottery: per-term diagnostics as optuna user_attrs every trial +
wean_trials.csv rows; winner verified in a FRESH PROCESS
(_verify_finalist.py; the stack's in-process vs CLI BLAS bifurcation
rule) before any claim.

Study: curr_w2l_contact2_r100 in reports_20261020/w2l_contact2/
optuna_w2l_contact2.db. Ladder (--ladder): wean the drive after a
bootstrap winner exists (reuses this driver's run_round).

Usage:
    D:\\Anaconda\\envs\\myo\\python.exe _w2l_contact2_campaign.py [--n=60]
    ... --ladder          (after r100 has a survivor: 0.85/0.7/0.6/...)
"""
from __future__ import annotations

import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WEAN = os.path.normpath(os.path.join(
    HERE, "..", "..", "reports_20261016", "w2l_wean"))
for p in (WEAN, HERE):
    if p not in sys.path:
        sys.path.insert(0, p)

import _w2l_wean_eval as EV       # noqa: E402  (metric + evaluate, verbatim)
import optuna                     # noqa: E402

optuna.logging.set_verbosity(optuna.logging.WARNING)

# the corrected net is a CONSTANT this campaign - set it on the runner's KV
# directly (evaluate() float-casts every knob it is handed, so the string
# must not ride the knobs dict).
EV.T.KV["net"] = "bilateralrg2"

DB = "sqlite:///" + os.path.join(HERE, "optuna_w2l_contact2.db").replace("\\", "/")
SEED = 20261020
DUR_TUNE, DUR_VERIFY = 20.0, 30.0
PY = sys.executable

SPACE = dict(
    te=(1.5, 6.0),          # RG extensor tonic drive (nA)
    tf=(2.0, 8.0),          # RG flexor tonic drive (nA; F > E: escape engine)
    ch_hc=(0.01, 1.0),      # heel -> ipsi extensor cascade (weak class)
    ch_ank=(0.1, 2.0),      # heel/toe -> ipsi ankle MN ext
    ch_contra=(0.01, 2.0),  # NEW heel -> contra RG flx (the antiphase edge)
    ctn_amp=(0.5, 6.0),     # contact-encoder amplitude (nA)
    cref=(20.0, 150.0),     # contact-encoder saturation force (N)
    ibnA=(0.0, 3.0),        # Ib group sensor current (nA)
    comm=(0.2, 2.0),        # commissural scale (c1 3.0*comm, V3 0.08*comm)
)

# Seed 1 = Ben's literal corrected-aproj defaults (KV defaults). Seeds 2/3 =
# the aff-lineage wean winners' shared knobs translated (contact families at
# Ben's values) - the drive/encoder optima may transfer across nets.
SEEDS = [
    dict(te=3.0, tf=4.0, ch_hc=0.08, ch_ank=1.0, ch_contra=0.08,
         ctn_amp=4.0, cref=50.0, ibnA=1.0, comm=1.0),
    dict(te=4.0, tf=5.0, ch_hc=0.08, ch_ank=1.0, ch_contra=0.08,
         ctn_amp=2.26014, cref=60.43445, ibnA=0.05332, comm=1.64379),
    dict(te=2.4, tf=3.0, ch_hc=0.08, ch_ank=1.0, ch_contra=0.08,
         ctn_amp=0.71708, cref=46.37426, ibnA=1.32101, comm=0.41304),
]

LADDER = [0.85, 0.70, 0.60, 0.50, 0.40, 0.30]


def knobs_of(dscale: float, p: dict, dur: float) -> dict:
    return dict(EV.BASE,
                dscale=dscale,
                te=float(p["te"]), tf=float(p["tf"]),
                ch_hc=float(p["ch_hc"]), ch_ank=float(p["ch_ank"]),
                ch_contra=float(p["ch_contra"]),
                ctn_amp=float(p["ctn_amp"]), cref=float(p["cref"]),
                ibnA=float(p["ibnA"]), comm=float(p["comm"]),
                dur_walk=dur)


def sname(dscale: float) -> str:
    return f"curr_w2l_contact2_r{int(round(dscale * 100)):03d}"


def fresh_verify(dscale: float, params: dict) -> dict:
    """Winner verification in a FRESH process (BLAS bifurcation rule).
    Includes EV.BASE (the pinned protocol knobs) exactly like knobs_of."""
    kn = dict(EV.BASE, dscale=dscale, dur_walk=DUR_VERIFY)
    kn.update({k: float(params[k]) for k in SPACE})
    tmp = os.path.join(HERE, "_finalist_knobs.json")
    json.dump(kn, open(tmp, "w"), indent=1)
    r = subprocess.run(
        [PY, os.path.join(HERE, "_verify_finalist.py"), tmp],
        capture_output=True, text=True, timeout=1800)
    for line in r.stdout.splitlines():
        if line.startswith("RESULT "):
            return json.loads(line[7:])
    raise RuntimeError(f"fresh verify failed:\n{r.stdout[-800:]}\n{r.stderr[-800:]}")


def run_round(dscale: float, seed_params: dict | None, ntrials: int) -> dict:
    study = optuna.create_study(
        study_name=sname(dscale), storage=DB, direction="maximize",
        load_if_exists=True,
        sampler=optuna.samplers.TPESampler(seed=SEED))
    have = len(study.trials)
    if have == 0:
        for sp in ([seed_params] if seed_params else []) + SEEDS:
            study.enqueue_trial(sp)
    need = max(ntrials - have, 0)
    if need == 0 and have == 0:
        need = 1     # never ask best_trial of an empty study

    def obj(trial):
        p = {k: trial.suggest_float(k, lo, hi)
             for k, (lo, hi) in SPACE.items()}
        m = EV.evaluate(knobs_of(dscale, p, DUR_TUNE),
                        tag=f"{sname(dscale)}#{trial.number}",
                        csv_path=os.path.join(HERE, "contact2_trials.csv"))
        for k, v in m.items():
            if not k.startswith("_") and v is not None:
                try:
                    trial.set_user_attr(k, v)
                except (TypeError, ValueError):
                    pass
        return float(m["obj"])

    if need > 0:
        study.optimize(obj, n_trials=need)
    best = study.best_trial
    out = dict(dscale=dscale, study=sname(dscale),
               n_trials=len(study.trials),
               params={k: round(float(best.params[k]), 5) for k in SPACE},
               obj20=float(best.value))
    m30 = fresh_verify(dscale, best.params)
    out["m30_fresh"] = {k: m30.get(k) for k in EV.METRIC_KEYS}
    out["survive30"] = bool(m30.get("survive"))
    path = os.path.join(HERE, f"round_best_r{int(round(dscale*100)):03d}.json")
    json.dump(out, open(path, "w", encoding="utf-8"), indent=1)
    print(f"== ROUND dscale={dscale:.2f} best obj20={out['obj20']:.1f} "
          f"survive30(fresh)={out['survive30']} -> {path}", flush=True)
    return out


def main() -> int:
    n = 60
    ladder = False
    for a in sys.argv[1:]:
        if a.startswith("--n="):
            n = int(a[4:])
        elif a == "--ladder":
            ladder = True
    r100 = run_round(1.0, None, n)
    if not ladder or not r100["survive30"]:
        return 0
    prev = r100["params"]
    for ds in LADDER:
        prev_scaled = dict(prev, te=prev["te"] * ds / 1.0, tf=prev["tf"] * ds / 1.0)
        r = run_round(ds, prev_scaled, 26)
        if not r["survive30"]:
            print(f"ladder death at dscale={ds:.2f}", flush=True)
            break
        prev = r["params"]
    return 0


if __name__ == "__main__":
    sys.exit(main())
