function fr_writeManifest(manFile, C, tc, CASES, layerIds, regionName)
%FR_WRITEMANIFEST run_0/manifest.json (weights snapshot + checksum, seed,
% budgets, group list, layer order, machine, refinement semantics).
%
% Checksum of record (deterministic across sessions, no toolbox):
% sum(uint8 bytes .* (1:n)) mod 2^53, with the full spec text embedded.

man = struct();
man.run = 'run_0_weights_placeholder';
man.created = datetime('now');
man.machine = getenv('COMPUTERNAME');
man.matlab = version();
man.campaign = C.camp;
man.objective_spec = fullfile(C.camp, 'objective_spec.json');
specBytes = fileread(fullfile(C.camp, 'objective_spec.json'));
b = uint8(specBytes);
idx = double(1:numel(b))';
man.weightsChecksum = sprintf(['sum(bytes.*(1:n)) mod 2^53 = %.0f, ' ...
    'n = %d'], mod(sum(double(b) .* idx), 2^53), numel(b));
man.weightsSnapshot = specBytes;
man.weightsStatus = ['PLACEHOLDER-PENDING-BEN (refinement re-solve ' ...
    'from checkpoints follows Ben''s weight ruling)'];
man.seed = C.rngSeed;
man.budgets = struct('solveEvals', C.solver.MaxFunctionEvaluations, ...
    'refineEvals', C.solver.refineMaxFunctionEvaluations, ...
    'refinementRounds', C.refinementRounds, ...
    'refineTolerance', C.refineTolerance, ...
    'MeshTolerance', C.solver.MeshTolerance, ...
    'StepTolerance', C.solver.StepTolerance);
man.parallel = struct('workers', C.parallelMaxWorkers, ...
    'envBeforePool', 'OMP_NUM_THREADS=1; MKL_NUM_THREADS=1', ...
    'layerLoop', 'sequential in the contract layerOrder', ...
    'withinLayer', ['parfor over groups (no mutual obstacles in ' ...
    'pass 1)']);
man.layerOrder = struct();
for r = 1:numel(layerIds)
    % JSON struct fields cannot carry slashes/spaces - sanitize
    man.layerOrder.(regexprep(regionName{r}, '[^A-Za-z0-9_]', '_')) = ...
        layerIds{r};
end
man.groups = struct('mapId', {}, 'group', {}, 'region', {}, ...
    'primaryDof', {}, 'seedMuscle', {}, 'nBPA', {}, 'diaStr', {}, ...
    'tackle', {}, 'note', {});
for c = 1:numel(CASES)
    cs = CASES(c);
    man.groups(end + 1) = struct('mapId', cs.groupMapId, ...
        'group', cs.group, 'region', cs.region, ...
        'primaryDof', cs.passes{1}.sweptCoord, ...
        'seedMuscle', cs.stockMuscles{1}, 'nBPA', cs.seed.nBPA, ...
        'diaStr', cs.diaStr, 'tackle', cs.hasTackle, ...
        'note', cs.note);
end
man.refinement = ['round 1 after the first deep-outward pass; ' ...
    'round-start snapshot envelopes of ALL other groups; per-group ' ...
    'revert when the retained objective degrades > refineTolerance'];
man.envelopeOfRecord = ['rigid branch envelope (fr_runLayered ' ...
    'convention); compliant envelope only when the rigid branch failed'];
man.xiContext = ['compliant branch = adopted Xi0-Xi3 ' ...
    '(target_contract.json xiSource); Xi4 waived'];
man.knownCaps = { ...
    ['envelope/overlap branch ring caps at 3 offsets: 4-branch ' ...
    'groups (glut_max3, vas_int) under-represent one branch']; ...
    ['moving path points (rect_fem_r-P3, vas_lat_r-P5) are ' ...
    'fixed-tracked rows at the default pose; declared behavior stays ' ...
    'in fr_evalRoute']; ...
    ['short routes (2 declared rows) carry the wired ' ...
    'zero-length-sleeve grid convention (hardware at brackets; bone ' ...
    'obstacle vacuous over zero segments)']; ...
    ['Xi3 couples the max-envelope deltaRoute through the class Xi0 ' ...
    'channel (stage-1 scope)']};
man.preflight = ['PASSED 2026-11-04 06:07 ' ...
    '(campaign_20261103/output/preflight27.log)'];
man.escapeCriterion = ['gate mean 0.177 s/eval -> 1.99 h serial; ' ...
    'x10 conservative bound + overheads = 20.1 h <= 36 h -> full-27 ' ...
    '(run_0/LAUNCH_DECISION.md)'];
txt = jsonencode(man, 'PrettyPrint', true);
fid = fopen(manFile, 'w');
fwrite(fid, txt, 'char');
fclose(fid);
end
